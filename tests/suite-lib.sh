# Запуск набора регрессии (подключается из regression.sh; самотест — regression-selftest.sh):
#   suite ИМЯ команда аргументы…
# Печатает заголовок «### ИМЯ», вывод набора и код выхода. Упавший набор (синтаксическая ошибка bash, фатальная
# ошибка PHP, любой код выхода не 0 без собственной строки FAIL) — строка «FAIL suite ИМЯ: …»: регрессия считает
# строки FAIL, и набор, не дошедший до проверок, больше не выглядит зелёным (надёжность, этап 5: так выпал smoke-write).
suite() {
  local name=$1 out rc
  shift
  echo "### $name"
  out=$("$@" 2>&1)
  rc=$?
  [ -n "$out" ] && printf '%s\n' "$out"
  if [ "$rc" -ne 0 ] && ! grep -q '^FAIL' <<<"$out"; then
    echo "FAIL suite $name: код выхода $rc без строки FAIL — набор упал, не закончив проверки"
  fi
  return 0
}
